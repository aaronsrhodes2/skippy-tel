"""Regenerate index.md and topics/*.md from the archive's front matter.

Both are pure functions of the conversation files, so they are rebuilt from
scratch on every run and never edited by hand.
"""
from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path

from memory.store import Archive, slugify

RECENT = 200


def _link(rel: Path, text: str, base: str = "") -> str:
    return f"[{text.replace(']', ')')}](<{base}{rel.as_posix()}>)"


def _row(rel: Path, meta: dict, base: str = "") -> str:
    topics = ", ".join(meta.get("topics") or [])
    summary = (meta.get("summary") or "").replace("|", "/")
    return (f"| {meta.get('updated', '')[:10]} | {meta.get('source', '')} | "
            f"{_link(rel, meta.get('title', 'Untitled'), base)} | {topics} | {summary} |")


def rebuild(archive: Archive) -> None:
    entries = sorted(archive.entries(), key=lambda e: e[1].get("updated", ""), reverse=True)
    by_topic: dict[str, list] = defaultdict(list)
    for rel, meta in entries:
        for topic in meta.get("topics") or []:
            by_topic[topic].append((rel, meta))

    topics_dir = archive.root / "topics"
    topics_dir.mkdir(parents=True, exist_ok=True)
    for stale in topics_dir.glob("*.md"):
        stale.unlink()
    for topic, items in by_topic.items():
        lines = [f"# {topic}\n", f"{len(items)} conversations, newest first.\n",
                 "| Updated | Source | Conversation | Topics | Summary |",
                 "|---|---|---|---|---|"]
        lines += [_row(rel, meta, "../") for rel, meta in items]
        (topics_dir / f"{slugify(topic)}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    sources = Counter(meta.get("source", "?") for _, meta in entries)
    lines = [
        "# Skippy Memory — index\n",
        "Generated by `python -m memory`. Do not edit; it is rebuilt on every ingest.\n",
        "## Sources\n",
        *[f"- **{src}**: {n} conversations" for src, n in sorted(sources.items())],
        "\n## Topics\n",
        *[f"- {_link(Path('topics') / f'{slugify(t)}.md', t)} ({len(items)})"
          for t, items in sorted(by_topic.items(), key=lambda kv: (-len(kv[1]), kv[0]))],
        f"\n## Recent conversations (latest {min(RECENT, len(entries))} of {len(entries)})\n",
        "| Updated | Source | Conversation | Topics | Summary |",
        "|---|---|---|---|---|",
        *[_row(rel, meta) for rel, meta in entries[:RECENT]],
    ]
    (archive.root / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
