"""Records one scene of Skippy's face and writes it as a C header for the box's skippy_puppet spike (and the Python render of the same frame to compare with).

    services/satellite/.venv/Scripts/python tools/puppet_export.py [state]      # default idle

Writes services/satellite/rooms/components/skippy_puppet/scene_data.h and .skippy-shots/puppet-ref.png.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "satellite"))

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

import face_render as fr  # noqa: E402
import puppet  # noqa: E402

state = sys.argv[1] if len(sys.argv) > 1 else "idle"
face = fr.Face()
face.set_state(state)
for i in range(60):
    face.tick(10_000 + i * 50)
img, ops = puppet.record(face)
big = {}
for op in ops:
    if op[0] == "I" and op[1].shape[0] * op[1].shape[1] > 20000:
        big.setdefault(id(op[1]), op[1])
sprites = {k: i for i, k in enumerate(big)}
scene = puppet.encode_scene(ops, sprites)
kinds = {"L": 0, "B": 0, "I": 0}
for op in ops:
    kinds[op[0]] += 1
print(f"{state}: {len(ops)} ops {kinds}, scene {len(scene)} bytes, longest polyline {max((len(o[1]) for o in ops if o[0] == 'L'), default=0)} points, sprites {len(big)}")


def arr(name: str, data: bytes) -> str:
    rows = [", ".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
    return f"static const uint8_t {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"


out = ["#pragma once", "#include <stdint.h>", "// generated by tools/puppet_export.py: one recorded scene and its sprites (the spike's test data)", ""]
out.append(arr("SCENE", scene))
for k, tile in enumerate(big.values()):
    h, w = tile.shape[:2]
    r, g, b = (tile[..., c].astype(np.uint16) for c in range(3))
    w565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    swapped = ((w565 & 0xFF) << 8) | (w565 >> 8)                      # the panel's own (byte swapped) word order: copied straight into the frame buffer
    out.append(f"static const int SPRITE{k}_W = {w}, SPRITE{k}_H = {h};")
    out.append(arr(f"SPRITE{k}_RGB", swapped.astype("<u2").tobytes()))
    out.append(arr(f"SPRITE{k}_A", tile[..., 3].astype(np.uint8).tobytes()))
    opaque = tile[..., 3] > 0                                         # per row: the first and last column that has anything (x0 > x1 for an empty row)
    x0s = [int(np.argmax(r)) if r.any() else 1 for r in opaque]
    x1s = [int(len(r) - 1 - np.argmax(r[::-1])) if r.any() else 0 for r in opaque]
    out.append(f"static const uint16_t SPRITE{k}_X0[] = {{{', '.join(map(str, x0s))}}};")
    out.append(f"static const uint16_t SPRITE{k}_X1[] = {{{', '.join(map(str, x1s))}}};")
dest = ROOT / "services" / "satellite" / "rooms" / "components" / "skippy_puppet"
dest.mkdir(parents=True, exist_ok=True)
(dest / "scene_data.h").write_text("\n".join(out), encoding="utf-8")
(ROOT / ".skippy-shots").mkdir(exist_ok=True)
Image.fromarray(img).save(ROOT / ".skippy-shots" / "puppet-ref.png")
print("wrote", dest / "scene_data.h", "and .skippy-shots/puppet-ref.png")
